"""Summarise benchmark runs: reads results/bench/*.json (one per run, written by bench/run.py) and writes
results/bench/summary.csv and results/bench/summary.md with, per method x instance: n_runs, n_feasible,
best / mean / std / median / worst evaluator cost over feasible runs, mean wall time, and the gap (%) of best
and mean to a reference value per instance (REF below; the source is looked up in records_verified.json and
printed). gap = 100 * (cost - ref) / ref; negative = below the reference.
    python -m bench.summarize [--dir results/bench] [--out results/bench/summary.csv]"""
import argparse, csv, glob, json, os
from collections import defaultdict
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["O7", "vC10a", "AB20", "SC30", "Du62"]
MORDER = ["construct", "swap", "ga", "sa", "cro", "mip", "cpsat", "ours_s1", "ours_s2", "ours",
          "ours_nos1", "ours_noelite", "ours_unif"]
REF = {"O7": 131.69, "vC10a": 18522.79, "AB20": 5021.17, "SC30": 3343.47, "Du62": 3635307.30}


def ref_sources():
    out = {}
    try:
        rec = json.load(open(os.path.join(ROOT, "records_verified.json")))
    except Exception:
        rec = {}
    for i, v in REF.items():
        src = [e for e in rec.get(i, []) if abs(float(e["value"]) - v) <= 0.01]
        out[i] = (f"{src[0]['src']} [comparable: {src[0].get('comparable')}]" if src else "not found in records_verified.json")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="results/bench"); ap.add_argument("--out", default=None)
    a = ap.parse_args(); out = a.out or os.path.join(a.dir, "summary.csv")
    g = defaultdict(list)
    for fn in glob.glob(os.path.join(a.dir, "*.json")):
        try:
            r = json.load(open(fn))
        except Exception:
            continue
        if isinstance(r, dict) and "method" in r and "instance" in r:
            g[(r["method"], r["instance"])].append(r)
    key = lambda k: (MORDER.index(k[0]) if k[0] in MORDER else 99, k[0], ORDER.index(k[1]) if k[1] in ORDER else 99)
    rows = []
    for (m, i) in sorted(g, key=key):
        rs = g[(m, i)]
        c = np.array([r["cost"] for r in rs if r.get("feasible")], float)
        ok = len(c) > 0; ref = REF.get(i)
        f2 = lambda v: f"{v:.2f}" if v is not None else ""
        st = dict(best=c.min() if ok else None, mean=c.mean() if ok else None, std=c.std(ddof=1) if len(c) > 1 else (0.0 if ok else None),
                  median=float(np.median(c)) if ok else None, worst=c.max() if ok else None)
        gap = lambda v: f"{100 * (v - ref) / ref:.2f}" if (v is not None and ref) else ""
        rows.append(dict(method=m, instance=i, n_runs=len(rs), n_feasible=len(c),
                         **{k: f2(v) for k, v in st.items()},
                         mean_wall=f"{np.mean([r['wall'] for r in rs]):.1f}",
                         ref=f2(ref), gap_best_pct=gap(st["best"]), gap_mean_pct=gap(st["mean"])))
    with open(out, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    srcs = ref_sources()
    md = os.path.splitext(out)[0] + ".md"
    with open(md, "w") as fh:
        fh.write("# Benchmark summary\n\nGenerated by `python -m bench.summarize` from `%s/*.json`. Costs are the independent "
                 "evaluator's (flp.evaluate), over feasible runs only. gap = 100 (cost - ref) / ref.\n\n" % a.dir)
        fh.write("Reference values:\n\n")
        for i in ORDER:
            fh.write(f"- {i}: {REF[i]:,.2f} — {srcs[i]}\n")
        for i in ORDER:
            sub = [r for r in rows if r["instance"] == i]
            if not sub: continue
            fh.write(f"\n## {i} (ref {REF[i]:,.2f})\n\n| method | feasible/runs | best | mean | std | median | worst | gap best % | gap mean % | mean wall s |\n|---|---|---|---|---|---|---|---|---|---|\n")
            for r in sub:
                fh.write(f"| {r['method']} | {r['n_feasible']}/{r['n_runs']} | {r['best']} | {r['mean']} | {r['std']} | {r['median']} | "
                         f"{r['worst']} | {r['gap_best_pct']} | {r['gap_mean_pct']} | {r['mean_wall']} |\n")
    for i in ORDER:
        print(f"reference {i}: {REF[i]} — {srcs[i]}")
    for r in rows:
        print(",".join(str(v) for v in r.values()))
    print("->", out, md)


if __name__ == "__main__":
    main()
